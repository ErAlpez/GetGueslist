const translatableAttributes = ["aria-label", "placeholder", "title", "alt", "message", "authError"] as const;

export function isLocale(value: string | undefined): value is Locale {
  return locales.some((locale) => locale.code === value);
}

export function translate(locale: Locale, text: string): string {
  const key = text.trim();
  if (!key) return text;

  const translated = translations[locale]?.[key]
    ?? extendedTranslations[locale]?.[key]
    ?? formTranslations[locale]?.[key]
    ?? authTranslations[locale]?.[key]
    ?? uiTranslations[locale]?.[key]
    ?? featureTranslations[locale]?.[key]
    ?? eventLogoTranslations[locale]?.[key]
    ?? eventAttachmentTranslations[locale]?.[key]
    ?? confirmationTranslations[locale]?.[key]
    ?? ticketEmailTranslations[locale]?.[key];

  if (translated === undefined) return text;
  const leadingWhitespace = text.match(/^\s*/)?.[0] ?? "";
  const trailingWhitespace = text.match(/\s*$/)?.[0] ?? "";
  return `${leadingWhitespace}${translated}${trailingWhitespace}`;
}

export function localizeNode(node: ReactNode, locale: Locale): ReactNode {
  if (typeof node === "string") return translate(locale, node);
  if (Array.isArray(node)) return Children.map(node, (child) => localizeNode(child, locale));
  if (!isValidElement(node)) return node;

  const element = node as ReactElement<{ children?: ReactNode; [key: string]: unknown }>;
  const props = { ...element.props };
  if (props.children !== undefined) props.children = localizeNode(props.children, locale);
  for (const attribute of translatableAttributes) {
    const value = props[attribute];
    if (typeof value === "string") props[attribute] = translate(locale, value);
  }
  return cloneElement(element, props);
}
